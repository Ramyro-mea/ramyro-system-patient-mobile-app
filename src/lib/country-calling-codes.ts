export function getCountryCallingCode(iso2: string) {
  return countryCallingCodes.find((country) => country.iso2 === iso2);
}

export function splitInternationalPhone(phoneNumber: string | null) {
  const value = phoneNumber?.trim() ?? '';
  if (!value.startsWith('+')) {
    return {
      countryIso: DEFAULT_COUNTRY_ISO,
      countryCode: DEFAULT_COUNTRY_CODE,
      nationalNumber: value.replace(/^0+/, ''),
    };
  }

  const preferredSharedCodes: Record<string, string> = {
    '+1': 'US',
    '+7': 'RU',
    '+39': 'IT',
  };
  const normalized = `+${value.replace(/\D/g, '')}`;
  const matches = countryCallingCodes
    .filter((country) => normalized.startsWith(country.callingCode))
    .sort((left, right) => right.callingCode.length - left.callingCode.length);
  const longestCode = matches[0]?.callingCode;
  const sameLengthMatches = matches.filter(
    (country) => country.callingCode === longestCode,
  );
  const preferredIso = longestCode ? preferredSharedCodes[longestCode] : undefined;
  const country =
    sameLengthMatches.find((item) => item.iso2 === preferredIso) ?? matches[0];

  if (!country) {
    return {
      countryIso: DEFAULT_COUNTRY_ISO,
      countryCode: DEFAULT_COUNTRY_CODE,
      nationalNumber: normalized.slice(1).replace(/^0+/, ''),
    };
  }

  return {
    countryIso: country.iso2,
    countryCode: country.callingCode,
    nationalNumber: normalized.slice(country.callingCode.length).replace(/^0+/, ''),
  };
}
